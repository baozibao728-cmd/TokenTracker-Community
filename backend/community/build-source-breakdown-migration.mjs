// Deterministic local generation only. Never reads credentials or connects.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const dir = path.dirname(fileURLToPath(import.meta.url));
export const sources = ['001_leaderboard_source_breakdown.sql'];
export const migrationPath = path.resolve(dir, '../deploy/migrations/20261011000000_community-leaderboard-source-breakdown.sql');
export const rollbackPath = path.join(dir, 'source-breakdown/rollback-generated.sql');
const legacySourcePath = path.join(dir, 'sql/004_read_rpc.sql');
const marker = 'CREATE FUNCTION public.community_leaderboard(';
const functionEnd = 'END $fn$;';
const normalize = value => value.replace(/\r\n/g, '\n');
const hash = value => createHash('sha256').update(value).digest('hex');

function readSources() {
  assert.deepEqual(fs.readdirSync(path.join(dir, 'source-breakdown')).filter(name => /^\d+_.*\.sql$/.test(name)).sort(), sources);
  return sources.map(name => {
    const source = normalize(fs.readFileSync(path.join(dir, 'source-breakdown', name), 'utf8'));
    return { name, source, digest: hash(source) };
  });
}

export function buildMigration() {
  const parts = readSources().map(({ name, source, digest }) =>
    `\n-- BEGIN SOURCE: backend/community/source-breakdown/${name} SHA256=${digest}\n${source}\n-- END SOURCE: backend/community/source-breakdown/${name}\n`).join('');
  return '-- GENERATED by backend/community/build-source-breakdown-migration.mjs. Do not edit.\n'
    + '-- Requires the reviewed 20261001000000 Community baseline. InsForge supplies one transaction.\n'
    + parts;
}

export function buildRollback() {
  const historical = normalize(fs.readFileSync(legacySourcePath, 'utf8'));
  const start = historical.indexOf(marker);
  assert.notEqual(start, -1, 'Historical Community source must retain its original leaderboard function');
  const end = historical.indexOf(functionEnd, start);
  assert.notEqual(end, -1, 'Historical Community source function terminator changed');
  const oldFunction = historical.slice(start, end + functionEnd.length);
  const rollbackFunction = oldFunction.replace(/^CREATE FUNCTION/m, 'CREATE OR REPLACE FUNCTION');
  assert.notEqual(rollbackFunction, oldFunction);
  return '-- GENERATED rollback companion. Never place this file in backend/deploy/migrations.\n'
    + `-- Restores the historical Community v1 RPC from backend/community/sql/004_read_rpc.sql SHA256=${hash(historical)}.\n`
    + '-- Apply only after the source-breakdown migration has been applied. This is one atomic CREATE OR REPLACE.\n'
    + rollbackFunction + '\n';
}

export function checkArtifacts() {
  assert.equal(normalize(fs.readFileSync(migrationPath, 'utf8')), buildMigration(), 'Source-breakdown migration drift: regenerate from reviewed SQL');
  assert.equal(normalize(fs.readFileSync(rollbackPath, 'utf8')), buildRollback(), 'Rollback artifact drift: regenerate from the historical v1 SQL');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (process.argv.includes('--check')) {
    checkArtifacts();
    console.log('PASS source-breakdown migration and historical rollback match their generators');
  } else {
    fs.mkdirSync(path.dirname(migrationPath), { recursive: true });
    fs.mkdirSync(path.dirname(rollbackPath), { recursive: true });
    fs.writeFileSync(migrationPath, buildMigration());
    fs.writeFileSync(rollbackPath, buildRollback());
    console.log('Generated additive source-breakdown migration and local rollback companion; nothing deployed');
  }
}
