// Local deterministic generation only. Never reads credentials or connects.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
export const dir = path.dirname(fileURLToPath(import.meta.url));
export const sources = ['001_tables.sql','002_membership_rpc.sql','003_transfer_rpc.sql','004_read_rpc.sql','005_permissions.sql'];
export const migrationPath = path.resolve(dir,'../deploy/migrations/20261001000000_community-leaderboard-v1.sql');
export function buildMigration() {
  assert.deepEqual(fs.readdirSync(path.join(dir,'sql')).filter(n=>n.endsWith('.sql')).sort(),sources);
  return '-- GENERATED by backend/community/build-migration.mjs. Do not edit.\n'
    + '-- Requires the reviewed TokenTracker MVP foundation. InsForge supplies one transaction.\n'
    + sources.map(name=>{
      const sql=fs.readFileSync(path.join(dir,'sql',name),'utf8').replace(/\r\n/g,'\n');
      return `\n-- BEGIN SOURCE: backend/community/sql/${name} SHA256=${createHash('sha256').update(sql).digest('hex')}\n${sql}\n-- END SOURCE: backend/community/sql/${name}\n`;
    }).join('');
}
export function checkMigration() {
  const actual=fs.readFileSync(migrationPath,'utf8').replace(/\r\n/g,'\n');
  assert.equal(actual,buildMigration(),'Community migration drift: regenerate from reviewed sources');
  return actual;
}
if(process.argv[1] && import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href) {
  if(process.argv.includes('--check')) {checkMigration(); console.log('PASS Community migration matches all five source SQL bodies');}
  else {fs.writeFileSync(migrationPath,buildMigration()); console.log('Generated Community incremental migration; nothing deployed');}
}
