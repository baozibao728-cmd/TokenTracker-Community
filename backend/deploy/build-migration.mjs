// Deterministic local build only. Never connects to a project or deploys SQL.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
export const deployDir = path.dirname(fileURLToPath(import.meta.url));
const bootstrapDir = path.resolve(deployDir, '../bootstrap');
export const sources = [
  '000_preflight.sql', '001_core_tables.sql', '002_device_identity.sql',
  '003_account_session_states.sql', '004_account_usage_rpc.sql', '005_user_profiles.sql',
  '006_leaderboard_tables.sql', '006a_leaderboard_upstream.sql', '006b_leaderboard_daily_replace.sql',
  '007a_leaderboard_rpc.sql', '007b_refresh_claim.sql', '008_permissions.sql',
];
export const migrationPath = path.join(deployDir, 'migrations/20260930000000_tokentracker-mvp-bootstrap.sql');
export function buildMigration() {
  const actual = fs.readdirSync(bootstrapDir).filter(n => /^\d{3}[a-z]?_.*\.sql$/.test(n)).sort();
  assert.deepEqual(actual, sources, 'Review the dependency order when adding/removing source SQL');
  const header = '-- GENERATED by backend/deploy/build-migration.mjs. Do not edit this artifact.\n'
    + '-- InsForge wraps this ONE migration in a transaction. No top-level BEGIN/COMMIT.\n'
    + '-- test-platform.sql is deliberately excluded; InsForge owns platform roles and auth.users.\n';
  const parts = sources.map(name => {
    const sql = fs.readFileSync(path.join(bootstrapDir, name), 'utf8').replace(/\r\n/g, '\n');
    const sha = createHash('sha256').update(sql).digest('hex');
    return `\n-- BEGIN SOURCE: backend/bootstrap/${name} SHA256=${sha}\n${sql}\n-- END SOURCE: backend/bootstrap/${name}\n`;
  });
  return header + parts.join('');
}
export function checkMigration() {
  const actual = fs.readFileSync(migrationPath, 'utf8').replace(/\r\n/g, '\n');
  assert.equal(actual, buildMigration(), 'Generated migration drift: regenerate from reviewed source SQL');
  // Exact source bodies in the reviewed order; the only additions are comments.
  // No SQL statements are inserted, removed or rewritten, including dollar-quoted bodies.
  return actual;
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (process.argv.includes('--check')) {
    checkMigration();
    console.log('PASS single migration contains exactly the 12 reviewed SQL bodies in dependency order');
  } else {
    fs.mkdirSync(path.dirname(migrationPath), { recursive: true });
    fs.writeFileSync(migrationPath, buildMigration());
    console.log('Generated backend/deploy/migrations/20260930000000_tokentracker-mvp-bootstrap.sql; nothing deployed');
  }
}
